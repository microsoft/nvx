"""Generate and check the microVM kernel's configuration against its inventory.

`kernel/config-microvm` is `make allnoconfig` with the settings of the kernel
feature inventory (`kernel_features.py`) as its fragment, and
`kernel/config-microvm.derived` records every other symbol that it sets with
the Kconfig rule that sets it. `configuration_problems` checks the two files
against the inventory without a kernel source, so that a symbol that neither
the inventory nor Kconfig sets fails the check on every change;
`check_build_configuration` regenerates both from a kernel source in the kernel
build and requires the build's configuration to match.
"""

from __future__ import annotations

import re
import shutil
from collections.abc import Iterable, Mapping
from dataclasses import dataclass
from pathlib import Path

from . import kconfig
from .common import ScriptError, run_checked
from .kernel_features import KERNEL_CONFIG_CHECKS, KERNEL_FEATURES, KernelFeature

CONFIG_PREFIX = "CONFIG_"
_SET = re.compile(r"^CONFIG_([A-Za-z0-9_]+)=(.*)$")
_NOT_SET = re.compile(r"^# CONFIG_([A-Za-z0-9_]+) is not set$")
_FEATURE_NAME = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
NOT_SET = "n"
# The derived record separates each assignment from its rule with this text,
# which no value of the configuration holds.
_REASON_SEPARATOR = "  # "
TOOLCHAIN_SYMBOL = "CC_VERSION_TEXT"
# The versions of the toolchain's other tools, whose probes decide symbols
# without a prompt too; a tool that is absent has version 0.
TOOL_VERSION_SYMBOLS = (
    "AS_VERSION",
    "LD_VERSION",
    "LLD_VERSION",
    "PAHOLE_VERSION",
    "RUSTC_VERSION",
    "RUSTC_LLVM_VERSION",
)
_TOOLCHAIN_HEADER = "# Toolchain: "
NO_PROMPT = "no prompt"
# The comment before the inventory's settings that the configuration does not
# write, because the toolchain that generated it hides their symbols.
HIDDEN_SETTINGS_COMMENT = (
    "#\n# Inventory settings whose symbols this configuration's toolchain hides\n#\n"
)
ARM_EXPLICIT_ADDITIONS = {
    "ARM64_4K_PAGES": "y",
    "ARM64_VA_BITS_48": "y",
    "ARM_GIC_V3": "y",
    "OF_RESERVED_MEM": "y",
    "NR_CPUS": "8",
    "HVC_NVX_MMIO": "y",
    "UNMAP_KERNEL_AT_EL0": "y",
    "MITIGATE_SPECTRE_BRANCH_HISTORY": "y",
    "ARM64_PTR_AUTH": "y",
}
DERIVED_HEADER = """\
# Generated by `python3 scripts/nvx.py kernel-config` from the kernel feature
# inventory, scripts/nvx_tools/kernel_features.py. Do not edit.
#
# Each symbol that kernel/config-microvm sets and that no inventory setting
# sets, with the Kconfig rule that sets it: `selected by` the symbols whose
# select applies; `implied by`; `choice default`, the default member of its
# choice; `default`, for a value that keeps its default, or for a symbol whose
# prompt is hidden, with the condition that hides it; or `no prompt`, for a
# symbol that no user can set, which its architecture, its toolchain, or other
# symbols decide.
"""


@dataclass(frozen=True, slots=True)
class Assignment:
    """One symbol's value in a configuration: `y`, `m`, `n` for a symbol
    that is not set, or the text of an `int`, `hex`, or `string` value as the
    configuration writes it."""

    symbol: str
    value: str

    @staticmethod
    def parse(line: str) -> Assignment | None:
        match = _SET.match(line)
        if match is not None:
            return Assignment(match.group(1), match.group(2))
        match = _NOT_SET.match(line)
        if match is not None:
            return Assignment(match.group(1), NOT_SET)
        return None

    @property
    def line(self) -> str:
        if self.value == NOT_SET:
            return f"# {CONFIG_PREFIX}{self.symbol} is not set"
        return f"{CONFIG_PREFIX}{self.symbol}={self.value}"

    def holds(self, values: Mapping[str, str]) -> bool:
        return values.get(self.symbol, NOT_SET) == self.value


def parse_config(text: str, source: str = "configuration") -> dict[str, str]:
    """Return the value of every symbol that a configuration assigns, `n` for
    one that it writes as not set."""
    values: dict[str, str] = {}
    for number, line in enumerate(text.splitlines(), start=1):
        assignment = Assignment.parse(line.strip())
        if assignment is None:
            if line.startswith(CONFIG_PREFIX):
                raise ScriptError(f"{source} line {number} is invalid: {line}")
            continue
        if assignment.symbol in values:
            raise ScriptError(
                f"{source} assigns {CONFIG_PREFIX}{assignment.symbol} twice"
            )
        values[assignment.symbol] = assignment.value
    return values


def _assignments(lines: Iterable[str], source: str) -> list[Assignment]:
    assignments: list[Assignment] = []
    for line in lines:
        assignment = Assignment.parse(line)
        if assignment is None:
            raise ScriptError(f"{source} has an invalid assignment: {line!r}")
        assignments.append(assignment)
    return assignments


def inventory_problems(
    features: tuple[KernelFeature, ...] = KERNEL_FEATURES,
    checks: Mapping[str, tuple[str, ...]] = KERNEL_CONFIG_CHECKS,
) -> list[str]:
    """Return what makes an inventory invalid: a feature without a name,
    summary, rationale, consumer, or validation, an invalid assignment, a
    symbol that two settings set, or an expectation that a setting
    contradicts."""
    problems: list[str] = []
    names: set[str] = set()
    owners: dict[str, tuple[str, Assignment]] = {}
    for feature in features:
        if not _FEATURE_NAME.match(feature.name):
            problems.append(f"feature name {feature.name!r} is not kebab-case")
        if feature.name in names:
            problems.append(f"feature {feature.name} is defined twice")
        names.add(feature.name)
        for field_name in ("summary", "rationale"):
            if not getattr(feature, field_name).strip():
                problems.append(f"feature {feature.name} has no {field_name}")
        for field_name in ("consumers", "validation"):
            entries: tuple[str, ...] = getattr(feature, field_name)
            if not entries or any(not entry.strip() for entry in entries):
                problems.append(
                    f"feature {feature.name} names no {field_name.rstrip('s')}"
                )
        if not feature.settings:
            problems.append(f"feature {feature.name} makes no setting")
        for line in feature.settings:
            assignment = Assignment.parse(line)
            if assignment is None:
                problems.append(f"feature {feature.name} sets {line!r}")
                continue
            if assignment.symbol in owners:
                other = owners[assignment.symbol][0]
                problems.append(
                    f"{CONFIG_PREFIX}{assignment.symbol} is set by both "
                    f"{other} and {feature.name}"
                )
                continue
            owners[assignment.symbol] = (feature.name, assignment)
    for feature in features:
        for line in feature.expects:
            assignment = Assignment.parse(line)
            if assignment is None:
                problems.append(f"feature {feature.name} expects {line!r}")
                continue
            owner = owners.get(assignment.symbol)
            if owner is not None and owner[1] != assignment:
                problems.append(
                    f"feature {feature.name} expects {line}, but {owner[0]} "
                    f"sets {owner[1].line}"
                )
    for check, members in checks.items():
        for member in members:
            if member not in names:
                problems.append(f"check {check} names unknown feature {member}")
    return problems


def inventory_settings(
    features: tuple[KernelFeature, ...] = KERNEL_FEATURES,
) -> dict[str, tuple[KernelFeature, Assignment]]:
    """Return each symbol that the inventory sets, with its feature."""
    settings: dict[str, tuple[KernelFeature, Assignment]] = {}
    for feature in features:
        for assignment in _assignments(feature.settings, feature.name):
            settings[assignment.symbol] = (feature, assignment)
    return settings


def render_fragment(features: tuple[KernelFeature, ...] = KERNEL_FEATURES) -> str:
    """Render the inventory's settings as a Kconfig fragment."""
    lines: list[str] = []
    for feature in features:
        lines.append(f"# {feature.name}: {feature.summary}")
        lines.extend(feature.settings)
    return "\n".join(lines) + "\n"


@dataclass(frozen=True, slots=True)
class DerivedRecord:
    """`kernel/config-microvm.derived`: the toolchain that generated the
    configuration, and each symbol that it sets beyond the inventory, with the
    rule that sets it."""

    toolchain: str | None
    entries: dict[str, tuple[Assignment, str]]

    @staticmethod
    def parse(text: str, source: str = "derived record") -> DerivedRecord:
        toolchain: str | None = None
        entries: dict[str, tuple[Assignment, str]] = {}
        for number, line in enumerate(text.splitlines(), start=1):
            if line.startswith(_TOOLCHAIN_HEADER):
                toolchain = line[len(_TOOLCHAIN_HEADER) :]
                continue
            if not line or line.startswith("#"):
                continue
            assignment_text, separator, reason = line.rpartition(_REASON_SEPARATOR)
            assignment = Assignment.parse(assignment_text) if separator else None
            if assignment is None or not reason:
                raise ScriptError(f"{source} line {number} is invalid: {line}")
            if assignment.symbol in entries:
                raise ScriptError(
                    f"{source} records {CONFIG_PREFIX}{assignment.symbol} twice"
                )
            entries[assignment.symbol] = (assignment, reason)
        return DerivedRecord(toolchain, entries)

    def render(self) -> str:
        lines = [DERIVED_HEADER.rstrip("\n"), "#"]
        if self.toolchain is not None:
            lines.append(f"{_TOOLCHAIN_HEADER}{self.toolchain}")
        for symbol in sorted(self.entries):
            assignment, reason = self.entries[symbol]
            lines.append(f"{assignment.line}{_REASON_SEPARATOR}{reason}")
        return "\n".join(lines) + "\n"


def configuration_problems(
    config_text: str,
    derived_text: str,
    features: tuple[KernelFeature, ...] = KERNEL_FEATURES,
    *,
    config_name: str = "kernel/config-microvm",
    derived_name: str = "kernel/config-microvm.derived",
) -> list[str]:
    """Check a configuration and its derived record against the inventory,
    without a kernel source: every setting and expectation of the inventory
    holds, and every symbol that the configuration sets is either an
    inventory setting or recorded, with the same value, as derived."""
    problems = inventory_problems(features)
    if problems:
        return problems
    try:
        values = parse_config(config_text, config_name)
        record = DerivedRecord.parse(derived_text, derived_name)
    except ScriptError as error:
        return [str(error)]
    settings = inventory_settings(features)
    for feature, assignment in settings.values():
        if not assignment.holds(values):
            problems.append(
                f"{config_name} does not hold {assignment.line}, which the "
                f"inventory's {feature.name} feature sets"
            )
    for feature in features:
        for assignment in _assignments(feature.expects, feature.name):
            if not assignment.holds(values):
                problems.append(
                    f"{config_name} does not hold {assignment.line}, on which "
                    f"the inventory's {feature.name} feature relies"
                )
    for symbol, value in values.items():
        if value == NOT_SET or symbol in settings:
            continue
        recorded = record.entries.get(symbol)
        line = Assignment(symbol, value).line
        if recorded is None:
            problems.append(
                f"{config_name} sets {line}, which neither the kernel feature "
                f"inventory nor {derived_name} accounts for: add it to a "
                "feature of scripts/nvx_tools/kernel_features.py, with its "
                "rationale, consumers, and validation, and regenerate both "
                "files with `nvx.py kernel-config`"
            )
        elif recorded[0].value != value:
            problems.append(
                f"{derived_name} records {recorded[0].line}, but {config_name} "
                f"sets {line}"
            )
    for symbol, (assignment, _) in record.entries.items():
        if symbol in settings:
            problems.append(
                f"{derived_name} records {assignment.line}, which the inventory sets"
            )
        elif values.get(symbol, NOT_SET) == NOT_SET:
            problems.append(
                f"{derived_name} records {assignment.line}, which {config_name} "
                "does not set"
            )
    toolchain = toolchain_identity(values)
    if toolchain is not None and record.toolchain != toolchain:
        problems.append(
            f"{derived_name} names the toolchain {record.toolchain!r}, but "
            f"{config_name} was generated with {toolchain!r}"
        )
    return problems


def arm_configuration_problems(
    config_text: str, derived_text: str, features: tuple[KernelFeature, ...]
) -> list[str]:
    """Audit actual ARM values and reject x86 leakage and unowned explicit additions."""
    problems = configuration_problems(
        config_text,
        derived_text,
        features,
        config_name="kernel/config-microvm-arm64",
        derived_name="kernel/config-microvm-arm64.derived",
    )
    values = parse_config(config_text, "ARM64 configuration")
    legacy_prefixes = (
        "X86",
        "IA32",
        "PARAVIRT",
        "PCI",
        "ACPI",
        "HYPERV_",
        "SERIAL_8250",
        "SERIAL_AMBA_PL011",
    )
    legacy = {
        "HVC_XE9",
        "EARLY_PRINTK",
        "DEVPORT",
        "DEVMEM",
        "HAS_IOPORT_MAP",
        "PVH",
        "XEN",
        "KVM_GUEST",
        "HYPERV",
        "HYPERVISOR_GUEST",
        "COMPAT",
        "HOTPLUG_CPU",
        "MEMORY_HOTPLUG",
        "EFI",
        "EFI_STUB",
        "EFI_RUNTIME_MAP",
        "EFIVAR_FS",
        "MODIFY_LDT_SYSCALL",
        "PCSPKR_PLATFORM",
        "PCMCIA",
    }
    for symbol, value in values.items():
        if value != NOT_SET and (
            symbol in legacy or symbol.startswith(legacy_prefixes)
        ):
            problems.append(
                f"ARM64 configuration enables excluded option CONFIG_{symbol}={value}"
            )
        if value == "m":
            problems.append(
                f"ARM64 configuration builds an unshipped module CONFIG_{symbol}=m"
            )
    if values.get("ARM64") != "y" or values.get("ARM64_4K_PAGES") != "y":
        problems.append(
            "ARM64 configuration does not select the required 64-bit/4-KiB binding"
        )
    if values.get("CMDLINE", '""') != '""':
        problems.append(
            "ARM64 configuration embeds a command line outside the machine profile"
        )
    common = inventory_settings()
    for symbol, (_, assignment) in inventory_settings(features).items():
        if assignment.value == NOT_SET or symbol in common:
            continue
        if ARM_EXPLICIT_ADDITIONS.get(symbol) != assignment.value:
            problems.append(
                f"ARM64 inventory adds an unnecessary or unreviewed {assignment.line}"
            )
    return problems


def toolchain_identity(values: Mapping[str, str]) -> str | None:
    """The toolchain that resolved a configuration, as its derived record
    names it: the compiler's version text, then the version of each other
    tool that the configuration records as present, or None when the
    configuration records no compiler."""
    compiler = values.get(TOOLCHAIN_SYMBOL)
    if compiler is None:
        return None
    tools = [
        f"{symbol}={values[symbol]}"
        for symbol in TOOL_VERSION_SYMBOLS
        if values.get(symbol, NOT_SET) not in ("0", NOT_SET)
    ]
    return "; ".join([_unquote(compiler), *tools])


def _unquote(value: str) -> str:
    if len(value) >= 2 and value[0] == value[-1] == '"':
        return value[1:-1]
    return value


def _kconfig_values(values: Mapping[str, str]) -> dict[str, str]:
    return {symbol: _unquote(value) for symbol, value in values.items()}


def derive(
    tree: kconfig.KconfigTree,
    values: Mapping[str, str],
    settings: Mapping[str, tuple[KernelFeature, Assignment]],
    *,
    require_known_symbols: bool = False,
) -> dict[str, tuple[Assignment, str]]:
    """Attribute each symbol that a generated configuration sets beyond the
    inventory's settings to the Kconfig rule that sets it."""
    evaluated = kconfig.ConfigValues(tree, _kconfig_values(values))
    entries: dict[str, tuple[Assignment, str]] = {}
    unexplained: list[str] = []
    for symbol, value in values.items():
        if value == NOT_SET or symbol in settings:
            continue
        if require_known_symbols and symbol not in tree.symbols:
            raise ScriptError(
                f"configuration sets unknown Kconfig symbol {Assignment(symbol, value).line}"
            )
        reason = _reason(tree, evaluated, symbol)
        if reason is None:
            unexplained.append(Assignment(symbol, value).line)
            continue
        entries[symbol] = (Assignment(symbol, value), reason)
    if unexplained:
        raise ScriptError(
            "Kconfig sets symbols that a user could set, beyond the inventory: "
            + ", ".join(unexplained)
        )
    return entries


def _reason(
    tree: kconfig.KconfigTree, values: kconfig.ConfigValues, symbol: str
) -> str | None:
    definition = tree.symbols.get(symbol)
    if definition is None or not definition.prompted:
        return NO_PROMPT
    selectors = kconfig.active_selectors(tree, values, symbol)
    if selectors:
        return "selected by " + ", ".join(selectors)
    if tree.choice_of(symbol) is not None:
        return "choice default"
    visibility = kconfig.prompt_visibility(tree, values, symbol)
    if visibility == kconfig.NO:
        implicators = kconfig.active_implicators(tree, values, symbol)
        if implicators:
            return "implied by " + ", ".join(implicators)
        conditions = kconfig.hidden_prompt_conditions(tree, values, symbol)
        return "default, prompt hidden by " + "; ".join(conditions)
    if visibility is None:
        return "default, prompt hidden by a toolchain probe"
    if definition.type in ("string", "int", "hex"):
        return "default"
    return None


@dataclass(frozen=True, slots=True)
class GeneratedConfig:
    """A configuration that the inventory generated, with its record."""

    text: str
    values: dict[str, str]
    record: DerivedRecord


def generate(
    source: Path,
    work: Path,
    features: tuple[KernelFeature, ...] = KERNEL_FEATURES,
    *,
    architecture: str = "x86_64",
) -> GeneratedConfig:
    """Generate the configuration from a patched kernel source: `make
    allnoconfig` with the inventory's settings as KCONFIG_ALLCONFIG, in the
    build directory `work`."""
    problems = inventory_problems(features)
    if problems:
        raise ScriptError(
            "the kernel feature inventory is invalid: " + "; ".join(problems)
        )
    if work.exists():
        shutil.rmtree(work)
    work.mkdir(parents=True)
    fragment = work / "inventory.config"
    fragment.write_text(render_fragment(features), encoding="utf-8")
    run_checked(
        [
            "make",
            "-s",
            "-C",
            source,
            f"O={work}",
            f"KCONFIG_ALLCONFIG={fragment}",
            *(("ARCH=arm64",) if architecture == "aarch64" else ()),
            "allnoconfig",
        ]
    )
    generated = (work / ".config").read_text(encoding="utf-8")
    values = parse_config(generated, "the generated configuration")
    settings = inventory_settings(features)
    unmet = [
        f"{assignment.line} ({feature.name})"
        for feature, assignment in settings.values()
        if not assignment.holds(values)
    ]
    if unmet:
        raise ScriptError(
            "Kconfig does not keep these inventory settings, whose dependencies "
            "the inventory does not meet: " + ", ".join(unmet)
        )
    hidden = [
        assignment.line
        for _, assignment in settings.values()
        if assignment.value == NOT_SET and assignment.symbol not in values
    ]
    text = generated
    if hidden:
        text = text.rstrip("\n") + "\n\n" + HIDDEN_SETTINGS_COMMENT
        text += "\n".join(sorted(hidden)) + "\n"
    tree = (
        kconfig.read_kconfig(source)
        if architecture == "x86_64"
        else kconfig.read_kconfig(source, srcarch="arm64", arch="arm64")
    )
    record = DerivedRecord(
        toolchain_identity(values),
        derive(
            tree,
            values,
            settings,
            require_known_symbols=architecture == "aarch64",
        ),
    )
    if architecture == "aarch64":
        problems = arm_configuration_problems(text, record.render(), features)
        if problems:
            raise ScriptError(
                "ARM64 configuration audit failed: " + "; ".join(problems)
            )
    return GeneratedConfig(text, values, record)


def check_build_configuration(
    source: Path,
    work: Path,
    effective: Path,
    derived: Path,
    features: tuple[KernelFeature, ...] = KERNEL_FEATURES,
    *,
    architecture: str = "x86_64",
) -> None:
    """Require the configuration that a kernel build resolved, `effective`,
    to be the one that the inventory generates with the same kernel source and
    toolchain, and the derived record to account for it.

    The record must match exactly when the build's toolchain is the one that
    generated it, as in CI's Docker build: the same compiler and the same
    versions of its other tools (`toolchain_identity`). Another toolchain may
    detect other capabilities, so then only its entries for symbols with a
    prompt, which the toolchain does not decide, must match, and every other
    entry must name a symbol without a prompt."""
    generated = (
        generate(source, work, features)
        if architecture == "x86_64"
        else generate(source, work, features, architecture=architecture)
    )
    resolved = parse_config(effective.read_text(encoding="utf-8"), str(effective))
    problems: list[str] = []
    for symbol in sorted(resolved.keys() | generated.values.keys()):
        built = resolved.get(symbol, NOT_SET)
        expected = generated.values.get(symbol, NOT_SET)
        if built != expected:
            problems.append(
                f"the build resolves {Assignment(symbol, built).line}, but the "
                f"inventory generates {Assignment(symbol, expected).line}"
            )
    recorded = DerivedRecord.parse(derived.read_text(encoding="utf-8"), str(derived))
    tree = (
        kconfig.read_kconfig(source)
        if architecture == "x86_64"
        else kconfig.read_kconfig(source, srcarch="arm64", arch="arm64")
    )
    exact = recorded.toolchain == generated.record.toolchain
    for symbol in sorted(recorded.entries.keys() | generated.record.entries.keys()):
        definition = tree.symbols.get(symbol)
        if architecture == "aarch64" and definition is None:
            problems.append(f"{derived} records unknown Kconfig symbol {symbol}")
            continue
        prompted = definition is not None and definition.prompted
        mine = recorded.entries.get(symbol)
        theirs = generated.record.entries.get(symbol)
        if not exact and not prompted:
            if mine is not None and mine[1] != NO_PROMPT:
                problems.append(
                    f"{derived} records {symbol} without a prompt as {mine[1]}"
                )
            continue
        if mine != theirs:
            problems.append(
                f"{derived} records {_describe(mine)} for {CONFIG_PREFIX}{symbol}, "
                f"but the inventory derives {_describe(theirs)}"
            )
    if problems:
        raise ScriptError(
            "the kernel configuration does not match its feature inventory; "
            "regenerate it with `nvx.py kernel-config`:\n  " + "\n  ".join(problems)
        )
    print(
        f">> kernel configuration matches its inventory "
        f"({len(inventory_settings(features))} settings, "
        f"{len(generated.record.entries)} derived symbols"
        + ("" if exact else ", toolchain-dependent entries not compared")
        + ")"
    )


def _describe(entry: tuple[Assignment, str] | None) -> str:
    if entry is None:
        return "nothing"
    return f"{entry[0].line} ({entry[1]})"


def summary(
    config_text: str,
    derived_text: str,
    features: tuple[KernelFeature, ...] = KERNEL_FEATURES,
) -> str:
    values = parse_config(config_text)
    record = DerivedRecord.parse(derived_text)
    settings = inventory_settings(features)
    enabled = [symbol for symbol, value in values.items() if value != NOT_SET]
    by_inventory = [symbol for symbol in enabled if symbol in settings]
    prompted = [
        symbol for symbol, (_, reason) in record.entries.items() if reason != NO_PROMPT
    ]
    return (
        f"{len(enabled)} symbols set: {len(by_inventory)} by the inventory's "
        f"{len(features)} features, {len(record.entries)} derived, "
        f"{len(prompted)} of them with a prompt"
    )
