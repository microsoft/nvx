class _JobTests(unittest.TestCase):
    """The package job and the publish job of a CI run, over a checkout and
    an in-memory crates.io."""

    def setUp(self) -> None:
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.temporary = Path(temporary.name)
        self.checkout = _Checkout(self.temporary / "repository")
        self.use(self.checkout)

    def use(self, checkout: _Checkout) -> None:
        root = self.temporary
        self.checkout = checkout
        # Each job runs on a runner of its own.
        self.work_dir = root / f"package-job-{checkout.root.name}"
        self.publish_dir = root / f"publish-job-{checkout.root.name}"
        self.output = root / "output"
        self.summary = root / "summary.md"
        self.crates_io = _CratesIo()
        self.cargo = _Cargo(self.checkout, self.crates_io)
        self.environment = {
            "GITHUB_OUTPUT": str(self.output),
            "GITHUB_STEP_SUMMARY": str(self.summary),
            "PATH": os.environ.get("PATH", ""),
            "NVX_BUNDLE": "skip",
            "NVX_BUNDLE_DIR": str(root / "bundle"),
            "NVX_BUNDLE_HYPERVISOR": "mshv",
        }

    def package(self, platform: str = "linux") -> crate_release.Plan:
        with patch.object(crate_release, "run_checked", self.cargo):
            return crate_release.package_release(
                self.checkout.root,
                self.work_dir,
                crates=self.checkout.crates,
                registry=self.crates_io.registry(),
                environment=self.environment,
                platform=platform,
            )

    def package_job(self) -> list[PackageState]:
        """Run the package job, and return the packages that it outputs, with
        a fresh checkout for the publish job."""
        self.package()
        outputs = self.outputs()
        self.checkout.restore()
        self.output.unlink()
        self.cargo.reset()
        return crate_release.read_states(outputs["packages"], "packages")

    def prepare(self, states: Sequence[PackageState]) -> bool:
        with patch.object(crate_release, "run_checked", self.cargo):
            return crate_release.prepare_release(
                self.checkout.root,
                self.publish_dir,
                states,
                crates=self.checkout.crates,
                registry=self.crates_io.registry(),
                environment=self.environment,
            )

    def publish(self, environment: Mapping[str, str] | None = None) -> None:
        with patch.object(crate_release, "run_checked", self.cargo):
            crate_release.publish_release(
                self.checkout.root,
                self.publish_dir,
                crates=self.checkout.crates,
                registry=self.crates_io.registry(),
                environment=(
                    {**self.environment, "CARGO_REGISTRY_TOKEN": "token"}
                    if environment is None
                    else environment
                ),
                index_timeout_seconds=0,
            )

    def outputs(self) -> dict[str, str]:
        if not self.output.exists():
            return {}
        lines = self.output.read_text(encoding="utf-8").splitlines()
        return {key: value for key, value in (line.split("=", 1) for line in lines)}

    def change_crate(self, path: str = "crate/src/lib.rs") -> str:
        self.checkout.write(path, f"//! Demo {self.checkout.head}.\n")
        return self.checkout.commit("Change the crate")


