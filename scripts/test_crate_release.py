# The modification time that Cargo gives every member of a package.
CARGO_MTIME = 1153704088


def _version(text: str) -> Version:
    return Version.parse(text)


class _Checkout:
    """A Git repository whose `crate/` directory holds a crate."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.crate_dir = root / "crate"
        root.mkdir(parents=True)
        self.git("init", "-q")
        for key, value in (
            ("user.email", "test@example.invalid"),
            ("user.name", "test"),
            ("commit.gpgsign", "false"),
            ("core.autocrlf", "false"),
        ):
            self.git("config", key, value)
        for path, text in CRATE_FILES.items():
            self.write(path, text)
        (root / "README.md").write_text("# repository\n", encoding="utf-8")
        self.commit("Add the crate")

    def git(self, *arguments: str) -> str:
        # `git status --porcelain` starts lines with spaces, so keep them.
        return subprocess.run(
            ["git", "-C", str(self.root), *arguments],
            check=True,
            capture_output=True,
            text=True,
        ).stdout.rstrip()

    def write(self, path: str, content: str | bytes) -> None:
        file = self.crate_dir / path
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_bytes(
            content.encode("utf-8") if isinstance(content, str) else content
        )

    def commit(self, message: str) -> str:
        self.git("add", "--all")
        self.git("commit", "-q", "--allow-empty", "-m", message)
        return self.head

    @property
    def head(self) -> str:
        return self.git("rev-parse", "HEAD")

    def status(self) -> str:
        return self.git("status", "--porcelain", "--untracked-files=all")

    def give_version(self, version: str) -> None:
        """Rewrite the version of the crate's manifest and lockfile."""
        for path in ("Cargo.toml", "Cargo.lock"):
            file = self.crate_dir / path
            file.write_bytes(
                crate_release.versioned_file(
                    path,
                    file.read_bytes(),
                    NAME,
                    _version(DECLARED),
                    _version(version),
                )
            )


def _archive(
    root: str,
    files: Mapping[str, bytes],
    *,
    members: Sequence[tarfile.TarInfo] = (),
) -> bytes:
    """Return a .crate archive, as deterministic as Cargo's."""
    buffer = io.BytesIO()
    with gzip.GzipFile(fileobj=buffer, mode="wb", mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode="w") as archive:
            for path, data in sorted(files.items()):
                info = tarfile.TarInfo(f"{root}/{path}")
                info.size = len(data)
                info.mtime = CARGO_MTIME
                info.mode = 0o644
                archive.addfile(info, io.BytesIO(data))
            for info in members:
                archive.addfile(info)
    return buffer.getvalue()


def _pack(
    checkout: _Checkout,
    *,
    allow_dirty: bool = True,
    transform: Callable[[dict[str, bytes]], None] | None = None,
) -> tuple[str, bytes]:
    """Pack the crate as `cargo package` does: the files that Git tracks in
    the crate's directory as the working tree holds them, the original
    manifest as Cargo.toml.orig, a generated manifest, and
    .cargo_vcs_info.json, which records whether the directory has changes."""
    manifest = crate_release.read_manifest(
        (checkout.crate_dir / "Cargo.toml").read_bytes(), "Cargo.toml"
    )
    dirty = bool(checkout.git("status", "--porcelain", "--", "crate"))
    if dirty and not allow_dirty:
        raise ScriptError("command failed with exit 101: cargo package")
    files = {
        path.removeprefix("crate/"): (checkout.root / path).read_bytes()
        for path in checkout.git("ls-files", "-z", "--", "crate").split("\0")
        if path
    }
    files["Cargo.toml.orig"] = files["Cargo.toml"]
    files["Cargo.toml"] = (
        f'[package]\nname = "{manifest.name}"\nversion = "{manifest.version}"\n'
    ).encode()
    git: dict[str, object] = {"sha1": checkout.head}
    if dirty:
        git["dirty"] = True
    files[".cargo_vcs_info.json"] = (
        json.dumps({"git": git, "path_in_vcs": "crate"}, indent=2) + "\n"
    ).encode()
    if transform is not None:
        transform(files)
    root = f"{manifest.name}-{manifest.version}"
    return root, _archive(root, files)


class _CratesIo:
    """crates.io's index and download server, in memory."""

    def __init__(self) -> None:
        self.index: list[dict[str, object]] = []
        self.packages: dict[str, bytes] = {}
        self.requests: list[str] = []

    def add(self, version: str, package: bytes, *, yanked: bool = False) -> None:
        self.index.append(
            {
                "name": NAME,
                "vers": version,
                "deps": [],
                "cksum": hashlib.sha256(package).hexdigest(),
                "features": {},
                "yanked": yanked,
                "links": None,
                "v": 2,
            }
        )
        self.packages[package_url(version)] = package

    def fetch(self, url: str) -> bytes | None:
        self.requests.append(url)
        if url == f"{crate_release.INDEX_URL}/{crate_release.index_path(NAME)}":
            if not self.index:
                return None
            return "".join(json.dumps(entry) + "\n" for entry in self.index).encode()
        return self.packages.get(url)

    def registry(self) -> crate_release.Registry:
        return crate_release.Registry(self.fetch, sleep=lambda _seconds: None)

    def release(
        self,
        checkout: _Checkout,
        version: str = DECLARED,
        *,
        yanked: bool = False,
        transform: Callable[[dict[str, bytes]], None] | None = None,
    ) -> None:
        """Publish the checkout's commit as `version`, as CI does."""
        if version != DECLARED:
            checkout.give_version(version)
        try:
            _root, package = _pack(checkout, transform=transform)
        finally:
            checkout.git("checkout", "--", "crate")
        self.add(version, package, yanked=yanked)


def package_url(version: str) -> str:
    return f"{crate_release.DOWNLOAD_URL}/{NAME}/{NAME}-{version}.crate"


class _Cargo:
    """`cargo package`, `cargo build`, and `cargo publish` over a checkout,
    as `run_checked` runs them."""

    def __init__(self, checkout: _Checkout, crates_io: _CratesIo) -> None:
        self.checkout = checkout
        self.crates_io = crates_io
        self.commands: list[list[str]] = []
        self.environments: list[dict[str, str]] = []
        # Changes the files of every package, as a broken packer would.
        self.transform: Callable[[dict[str, bytes]], None] | None = None
        # Changes what an upload stores, as a broken registry would; None
        # stores nothing.
        self.store: Callable[[bytes], bytes | None] = lambda package: package

    def __call__(
        self,
        args: Sequence[str | os.PathLike[str]],
        *,
        cwd: Path | None = None,
        env: Mapping[str, str] | None = None,
        input_bytes: bytes | None = None,
    ) -> None:
        command = [os.fspath(arg) for arg in args]
        self.commands.append(command)
        self.environments.append(dict(env or {}))
        if command[:2] == ["cargo", "build"]:
            manifest = Path(command[command.index("--manifest-path") + 1])
            if not manifest.is_file():
                raise ScriptError(f"{manifest} does not exist")
            return
        if command[:2] not in (["cargo", "package"], ["cargo", "publish"]):
            raise AssertionError(f"unexpected command {command}")
        root, package = _pack(
            self.checkout,
            allow_dirty="--allow-dirty" in command,
            transform=self.transform,
        )
        if command[1] == "package":
            target = Path(command[command.index("--target-dir") + 1])
            path = target / "package" / f"{root}.crate"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(package)
            return
        stored = self.store(package)
        if stored is not None:
            self.crates_io.add(root.removeprefix(f"{NAME}-"), stored)

    def subcommands(self) -> list[str]:
        return [command[1] for command in self.commands]

    def reset(self) -> None:
        self.commands.clear()
        self.environments.clear()


class _Response:
    def __init__(self, body: bytes) -> None:
        self.body = body

    def __enter__(self) -> "_Response":
        return self

    def __exit__(self, *_exception: object) -> None:
        return None

    def read(self) -> bytes:
        return self.body


