class VersionTests(unittest.TestCase):
    def test_versions_parse_and_print_as_semver(self):
        for text in ("0.1.0", "0.1.0-alpha.3", "1.2.3-rc.1+build.5", "1.0.0-x-y.0"):
            with self.subTest(text=text):
                self.assertEqual(str(_version(text)), text)
        self.assertEqual(
            _version("1.2.3-alpha.4+meta"),
            Version(1, 2, 3, ("alpha", "4"), "meta"),
        )
        for text in ("1.2", "01.2.3", "1.2.3-01", "1.2.3-", "1.2.3+", "v1.2.3", ""):
            with self.subTest(text=text):
                with self.assertRaisesRegex(ScriptError, "is not a SemVer version"):
                    _version(text)

    def test_precedence_follows_semver(self):
        # The example of SemVer 2.0's item 11.
        ordered = [
            "1.0.0-alpha",
            "1.0.0-alpha.1",
            "1.0.0-alpha.beta",
            "1.0.0-beta",
            "1.0.0-beta.2",
            "1.0.0-beta.11",
            "1.0.0-rc.1",
            "1.0.0",
            "1.0.1-alpha.1",
            "1.1.0",
            "2.0.0",
        ]
        keys = [_version(text).precedence for text in ordered]
        self.assertEqual(keys, sorted(keys))
        self.assertEqual(len(set(keys)), len(keys))
        self.assertEqual(
            _version("1.0.0-alpha.1+one").precedence,
            _version("1.0.0-alpha.1+two").precedence,
        )

    def test_only_label_and_number_prereleases_count(self):
        self.assertEqual(_version("0.1.0-alpha.3").counter, ("alpha", 3))
        self.assertEqual(_version("0.1.0-alpha.3+meta").counter, ("alpha", 3))
        for text in (
            "0.1.0",
            "0.1.0-alpha",
            "0.1.0-3.alpha",
            "0.1.0-alpha.beta",
            "0.1.0-alpha.3.1",
            "0.1.0-3.4",
        ):
            with self.subTest(text=text):
                self.assertIsNone(_version(text).counter)


class NextVersionTests(unittest.TestCase):
    def next(self, declared: str, *published: str) -> str:
        return str(
            crate_release.next_version(
                _version(declared), [_version(text) for text in published]
            )
        )

    def test_the_declared_version_is_the_floor(self):
        self.assertEqual(self.next("0.1.0-alpha.3"), "0.1.0-alpha.3")
        self.assertEqual(
            self.next("0.1.0-alpha.3", "0.1.0-alpha.1", "0.1.0-alpha.2"),
            "0.1.0-alpha.3",
        )
        self.assertEqual(self.next("0.1.0-alpha.9", "0.1.0-alpha.4"), "0.1.0-alpha.9")

    def test_each_version_takes_the_next_number(self):
        self.assertEqual(
            self.next("0.1.0-alpha.3", "0.1.0-alpha.2", "0.1.0-alpha.3"),
            "0.1.0-alpha.4",
        )
        self.assertEqual(
            self.next("0.1.0-alpha.3", "0.1.0-alpha.11", "0.1.0-alpha.3"),
            "0.1.0-alpha.12",
        )
        # crates.io ignores build metadata, so its number is taken too.
        self.assertEqual(
            self.next("0.1.0-alpha.3", "0.1.0-alpha.5+build"), "0.1.0-alpha.6"
        )

    def test_other_series_do_not_count(self):
        self.assertEqual(self.next("0.2.0-alpha.1", "0.1.0-alpha.7"), "0.2.0-alpha.1")
        self.assertEqual(self.next("0.1.0-beta.1", "0.1.0-alpha.7"), "0.1.0-beta.1")
        self.assertEqual(
            self.next("0.1.0-alpha.3", "0.1.0-alpha.2.1", "0.1.0-alpha.4"),
            "0.1.0-alpha.5",
        )

    def test_a_declared_version_behind_crates_io_fails(self):
        # A version of another form, which takes no number, still sorts.
        for published in ("0.1.0-beta.1", "0.1.0", "0.2.0-alpha.1", "0.1.0-alpha.7.1"):
            with self.subTest(published=published):
                with self.assertRaisesRegex(
                    ScriptError,
                    rf"^0\.1\.0-alpha\.4, the next version of the declared "
                    rf"0\.1\.0-alpha\.3, would not be newer than {published}",
                ):
                    self.next("0.1.0-alpha.3", "0.1.0-alpha.3", published)

    def test_only_counted_prereleases_can_be_declared(self):
        for declared in ("0.1.0", "0.1.0-alpha", "0.1.0-alpha.3+meta", "1.0.0-rc"):
            with self.subTest(declared=declared):
                with self.assertRaisesRegex(ScriptError, "X.Y.Z-LABEL.N"):
                    self.next(declared)


class ManifestTests(unittest.TestCase):
    def rewrite(self, text: str, names: Sequence[str] = (NAME,)) -> str:
        return crate_release.rewrite_manifest(
            text.encode(),
            "Cargo.toml",
            names,
            _version(DECLARED),
            _version("0.1.0-alpha.4"),
        ).decode()

    def test_rewrites_only_the_package_version(self):
        for line_ending in ("\n", "\r\n"):
            with self.subTest(line_ending=repr(line_ending)):
                original = MANIFEST.replace("\n", line_ending)
                rewritten = self.rewrite(original)
                self.assertEqual(
                    _changed_lines(original.encode(), rewritten.encode()),
                    [b'version = "0.1.0-alpha.4" # the floor of CI\'s versions'],
                )
                self.assertTrue(rewritten.endswith(line_ending))

    def test_rewrites_the_workspace_version_and_exact_requirements(self):
        names = ("base", "demo")
