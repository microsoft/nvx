    def test_waits_until_the_index_lists_a_version(self):
        crates_io = _CratesIo()
        crates_io.add("1.0.0", b"one")
        now = [0.0]
        polls: list[float] = []

        def sleep(seconds: float) -> None:
            polls.append(seconds)
            now[0] += seconds
            if len(polls) == 3:
                crates_io.add("1.0.1", b"two")

        registry = crate_release.Registry(
            crates_io.fetch, sleep=sleep, clock=lambda: now[0]
        )
        release = registry.wait_for(
            NAME, _version("1.0.1"), timeout_seconds=100, interval_seconds=10
        )
        self.assertEqual(release.checksum, hashlib.sha256(b"two").hexdigest())
        self.assertEqual(polls, [10, 10, 10])
        with self.assertRaisesRegex(
            ScriptError, "the crates.io index did not list demo 1.0.2 within 25 s"
        ):
            registry.wait_for(
                NAME, _version("1.0.2"), timeout_seconds=25, interval_seconds=10
            )

    def test_fetches_retry_transient_failures(self):
        sleeps: list[float] = []

        def fetch(
            *responses: object, missing_codes: tuple[int, ...] = (404,)
        ) -> tuple[bytes | None, MagicMock]:
            with patch.object(
                crate_release.urllib.request, "urlopen", side_effect=responses
            ) as urlopen:
                result = crate_release.fetch_url(
                    "https://example.invalid/file",
                    missing_codes=missing_codes,
                    retry_seconds=1,
                    sleep=sleeps.append,
                )
            return result, urlopen

        result, urlopen = fetch(_Response(b"body"))
        self.assertEqual(result, b"body")
        request = urlopen.call_args.args[0]
        self.assertEqual(request.get_header("User-agent"), crate_release.USER_AGENT)
        self.assertEqual(request.get_header("Cache-control"), "no-cache")
        self.assertIsNone(fetch(_http_error(404))[0])
        self.assertIsNone(fetch(_http_error(403), missing_codes=(403, 404))[0])
        result, urlopen = fetch(
            _http_error(503), urllib.error.URLError("reset"), _Response(b"body")
        )
        self.assertEqual(result, b"body")
        self.assertEqual(urlopen.call_count, 3)
        self.assertEqual(sleeps, [1, 1])
        for code in (400, 403):
            with self.subTest(code=code):
                with self.assertRaisesRegex(ScriptError, f"failed: HTTP {code}"):
                    fetch(_http_error(code))
        with self.assertRaisesRegex(ScriptError, "failed 3 times: .*down"):
            fetch(*[urllib.error.URLError("down")] * 3)

